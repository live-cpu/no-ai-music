# ============================== 순수 함수 ==============================
def clean_text(value, limit=200):
    text = html.unescape(str(value or ""))
    return CONTROL_CHARS.sub(" ", text).strip()[:limit]


def csv_safe(value):
    text = str(value or "")
    return "'" + text if text and text[0] in ("=", "+", "-", "@", "\t", "\r") else text


def parse_iso_duration(value):
    match = ISO_DURATION_PATTERN.fullmatch(value or "")
    if not match:
        return 0
    days, hours, minutes, seconds = (int(p or 0) for p in match.groups())
    return days * 86400 + hours * 3600 + minutes * 60 + seconds


def quota_date_key():
    """Google 할당량 초기화 기준(태평양시) 날짜."""
    try:
        from zoneinfo import ZoneInfo
        now = datetime.now(ZoneInfo("America/Los_Angeles"))
    except Exception:
        now = datetime.now()
    return now.strftime("%Y-%m-%d")


def query_hash(query):
    return hashlib.sha256(" ".join(query.lower().split()).encode("utf-8")).hexdigest()


def is_safe_youtube_url(url):
    try:
        p = urlparse(url)
        return (p.scheme == "https" and p.hostname in ("youtube.com", "www.youtube.com")
                and p.username is None and p.password is None and p.port in (None, 443))
    except (ValueError, TypeError):
        return False


def build_playlist_url(video_ids):
    ids = [v for v in video_ids if isinstance(v, str) and VIDEO_ID_PATTERN.fullmatch(v)][:PLAYLIST_LIMIT]
    if not ids:
        return None
    url = "https://www.youtube.com/watch_videos?" + urlencode({"video_ids": ",".join(ids)}, safe=",")
    return url if is_safe_youtube_url(url) else None


def evaluate_ai_score(snippet, synthetic=False):
    """반환: (AI 의심 점수, 상태[유지/보류/제외], 근거). 참고용이며 확정 판정이 아님."""
    if synthetic:
        return 100, "제외", "YouTube 공식 합성 콘텐츠 라벨(status.containsSyntheticMedia)"

    title = clean_text(snippet.get("title", ""), 500)
    description = clean_text(snippet.get("description", ""), 1500)
    channel = clean_text(snippet.get("channelTitle", ""), 200)

    text = NEGATION_PATTERN.sub(" ", f"{title} {description}".lower())[:2000]

    score = 0
    reasons = []
    notes = []

    for pattern, points, label in AI_PATTERNS:
        if pattern.search(text):
            score += points
            reasons.append(f"{label}(+{points})")

    # 일반 문구일 수 있어 AI/인공지능 언급이 함께 있을 때만 인정
    if "새롭게 생성되었습니다" in text and AI_CONTEXT_PATTERN.search(text):
        score += 100
        reasons.append("AI 생성 안내 문구(+100)")

    strong_ai = score >= 50  # 확정 증거 여부 (공식 출처 감점 전에 판단)

    is_official = False
    channel_lower = channel.lower()
    if "vevo" in channel_lower or "official artist" in channel_lower or channel.endswith(" - Topic"):
        score -= 25
        reasons.append("공식 유통망/Topic 출처(-25)")
        is_official = True

    if OFFICIAL_WORK_PATTERN.search(text):
        score -= 35
        reasons.append("공식 사운드트랙 표기(-35)")
        is_official = True

    published = snippet.get("publishedAt", "")
    if published:
        try:
            pub_date = datetime.strptime(published[:10], "%Y-%m-%d")
            if datetime.now() - pub_date > timedelta(days=5 * 365):
                score -= 20
                reasons.append("5년 이상 전 업로드(-20)")
        except (ValueError, TypeError):
            pass

    if AUTO_GENERATED_PATTERN.search(text):
        notes.append("YouTube 자동 생성 영상 표기(AI 작곡의 증거 아님)")

    score = max(0, min(score, 100))
    detail = ", ".join(reasons + notes) or "특이사항 없음"

    if score >= 50 and is_official:
        status, prefix = "보류", "판정 충돌(AI 단서 + 공식 출처)"
    elif score >= 75:
        status, prefix = "제외", "AI 생성 강력 의심"
    elif score >= 50:
        status, prefix = "제외", "AI 의심 높음"
    elif score >= 25:
        status, prefix = "보류", "판정 불확실"
    else:
        status, prefix = "유지", "AI 생성 단서 낮음(확인 불가)"

    # --- 콘텐츠 종류 보정: 음원 증거가 없을 때만 적용 ---
    if status != "제외" and not strong_ai:
        has_music_evidence = is_official or bool(MUSIC_EVIDENCE_PATTERN.search(text))
        if not has_music_evidence:
            non_music = NON_MUSIC_PATTERN.search(text)
            if non_music:
                status = "제외"
                prefix = f"음악이 아닌 영상 추정('{non_music.group(0)[:20]}')"
            elif MOVIE_PATTERN.search(text) and status == "유지":
                status = "보류"
                prefix = "영화·드라마 관련 영상: 음원(OST) 여부 확인 필요"

    return score, status, f"{prefix}: {detail}"


def keyring_backend_status():
    """사용 가능한 보안 저장소가 있는지 확인. 평문/실패/null 백엔드는 허용하지 않는다."""
    try:
        backend = keyring.get_keyring()
        candidates = getattr(backend, "backends", None)
        candidates = list(candidates) if candidates is not None else [backend]
        for candidate in candidates:
            ident = f"{type(candidate).__module__}.{type(candidate).__name__}".lower()
            if any(hint in ident for hint in INSECURE_BACKEND_HINTS):
                continue
            try:
                if candidate.priority <= 0:
                    continue
            except Exception:
                continue
            return True, ""
    except Exception:
        pass
    return False, "사용 가능한 OS 보안 저장소가 없습니다. API 키를 안전하게 저장할 수 없습니다."


