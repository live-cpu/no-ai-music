    def show_results(self, videos):
        for widget in self.scroll_frame.winfo_children():
            widget.destroy()
        self.current_videos = []
        for index, original in enumerate(videos):
            video = dict(original)
            video["status_var"] = ctk.StringVar(master=self, value=video["status"])
            self.current_videos.append(video)
            self.render_video_row(index, video)

    def render_video_row(self, index, video):
        row = ctk.CTkFrame(self.scroll_frame)
        row.pack(fill="x", padx=5, pady=5)
        row.grid_columnconfigure(0, weight=1)

        title = video["title"] if len(video["title"]) <= 70 else video["title"][:67] + "..."
        ctk.CTkLabel(row, text=f"{index + 1}. {title}\n   {video['channel']} | AI 의심 점수: {video['score']}점",
                     anchor="w", justify="left", wraplength=650, font=("Arial", 12)
                     ).grid(row=0, column=0, padx=10, pady=6, sticky="ew")

        radios = ctk.CTkFrame(row, fg_color="transparent")
        radios.grid(row=0, column=1, padx=8, sticky="e")
        for column, (label, color) in enumerate([("유지", "green"), ("보류", "orange"), ("제외", "red")]):
            ctk.CTkRadioButton(radios, text=label, value=label, variable=video["status_var"],
                               fg_color=color, width=65).grid(row=0, column=column, padx=3, pady=3)

        ctk.CTkLabel(row, text=f"판정 근거: {video['reason']}", font=("Arial", 11), text_color="gray",
                     wraplength=850, justify="left").grid(row=1, column=0, columnspan=2, padx=10,
                                                          pady=(0, 7), sticky="w")

