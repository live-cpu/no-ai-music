    def process_api_response(self, data, qh, details):
        videos = []
        shorts = 0
        with self.db() as conn:
            for item in data.get("items", []):
                vid = (item.get("id") or {}).get("videoId", "")
                if not VIDEO_ID_PATTERN.fullmatch(str(vid)):
                    continue
                snippet = item.get("snippet") or {}
                title = clean_text(snippet.get("title"), 500)
                channel = clean_text(snippet.get("channelTitle"), 200)
                description = clean_text(snippet.get("description"), 1500)
                info = (details or {}).get(vid) or {}

                duration = info.get("duration", 0)
                if (0 < duration <= SHORTS_MAX_SECONDS
                        or SHORTS_TAG_PATTERN.search(f"{title} {description}")):
                    shorts += 1
                    continue

                score, status, reason = evaluate_ai_score(
                    {"title": title, "description": description, "channelTitle": channel,
                     "publishedAt": snippet.get("publishedAt", "")},
                    synthetic=info.get("synthetic", False))
                videos.append({"id": vid, "title": title, "channel": channel,
                               "score": score, "status": status, "reason": reason})

                if details is not None:  # 상세정보 조회 실패 시에는 캐시하지 않음
                    conn.execute(
                        "INSERT OR REPLACE INTO video_cache (video_id, title, channel_name, ai_score, "
                        "status, reason, rule_version, saved_at) VALUES (?, ?, ?, ?, ?, ?, ?, CURRENT_TIMESTAMP)",
                        (vid, title, channel, score, status, reason, RULE_VERSION))

            if videos and details is not None:
                conn.execute("INSERT OR REPLACE INTO query_cache (query_hash, video_ids, saved_at) "
                             "VALUES (?, ?, CURRENT_TIMESTAMP)",
                             (qh, json.dumps([v["id"] for v in videos])))
        return videos, shorts

    def load_query_cache(self, qh):
        with self.db() as conn:
            row = conn.execute("SELECT video_ids FROM query_cache WHERE query_hash = ? "
                               "AND saved_at > datetime('now', ?)", (qh, f"-{QUERY_TTL_DAYS} days")).fetchone()
            if not row:
                return None
            try:
                ids = json.loads(row[0])
            except (ValueError, TypeError):
                return None
            if not isinstance(ids, list):
                return None
            videos = []
            for vid in ids:
                if not isinstance(vid, str) or not VIDEO_ID_PATTERN.fullmatch(vid):
                    return None
                cached = conn.execute(
                    "SELECT title, channel_name, ai_score, status, reason FROM video_cache "
                    "WHERE video_id = ? AND rule_version = ? AND saved_at > datetime('now', ?)",
                    (vid, RULE_VERSION, f"-{VIDEO_TTL_DAYS} days")).fetchone()
                if not cached:
                    return None  # 일부라도 없으면 검색 전체를 다시 수행
                videos.append({"id": vid, "title": cached[0], "channel": cached[1], "score": cached[2],
                               "status": cached[3], "reason": f"[캐시] {cached[4]}"})
            return videos

