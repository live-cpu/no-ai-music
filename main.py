    def execute_youtube_search(self):
        if self.is_searching:
            return
        if not self.db_ok:
            self.update_status("데이터베이스를 사용할 수 없어 검색할 수 없습니다.", "red")
            return
        raw_query = clean_text(self.search_entry.get(), 100)
        if not raw_query:
            self.update_status("검색어를 입력해 주세요.", "orange")
            return

        qh = query_hash(raw_query)  # 원문 검색어는 저장하지 않음
        try:
            cached = self.load_query_cache(qh)
        except sqlite3.Error as exc:
            self.update_status(f"캐시 조회 실패: {type(exc).__name__}", "red")
            return
        if cached is not None:
            self.show_results(cached)
            self.update_status("캐시에서 결과를 불러왔습니다. API 호출 없음.", "green")
            return

        api_key = self.get_api_key()
        if not api_key:
            self.update_status("먼저 유효한 API 키를 보안 저장소에 저장하세요.", "orange")
            return
        if self.get_today_search_count() >= MAX_DAILY_SEARCHES:
            self.update_status("오늘의 검색 한도에 도달했습니다.", "red")
            return

        try:
            self.increment_search_count()  # UI 갱신이 포함되므로 반드시 메인 스레드에서 수행
        except sqlite3.Error as exc:
            self.update_status(f"검색 횟수 기록 실패: {type(exc).__name__}", "red")
            return

        query = raw_query + (AI_QUERY_SUFFIX if EXCLUDE_AI_TERMS_IN_QUERY else "")
        self.set_busy(True)
        self.update_status("YouTube 검색 중...")
        threading.Thread(target=self._search_worker, args=(api_key, query, qh), daemon=True).start()
        self.after(100, self._poll_result)

    def _search_worker(self, api_key, query, qh):
        """UI 를 직접 조작하지 않고 결과만 큐로 전달한다."""
        headers = {"x-goog-api-key": api_key}  # 키를 URL 에 넣지 않음
        params = {"part": "snippet", "q": query, "maxResults": MAX_RESULTS,
                  "type": "video", "videoCategoryId": "10"}
        try:
            resp = requests.get(SEARCH_URL, params=params, headers=headers, timeout=REQUEST_TIMEOUT)
            if resp.status_code != 200:
                self.result_queue.put(("error", f"YouTube 검색 오류 (HTTP {resp.status_code}): "
                                       f"{self._api_error_message(resp)}", True))
                return
            data = resp.json()
            details = self._fetch_video_details(headers, data)
            self.result_queue.put(("ok", data, qh, details))
        except requests.ConnectionError:
            self.result_queue.put(("error", "네트워크 연결 오류: 인터넷 연결 및 방화벽을 확인하세요.", True))
        except requests.RequestException:
            self.result_queue.put(("error", "네트워크 오류 또는 응답 시간 초과.", False))
        except (ValueError, TypeError):
            self.result_queue.put(("error", "YouTube API 응답을 해석할 수 없습니다.", False))
        except Exception as exc:
            self.result_queue.put(("error", f"검색 처리 오류: {type(exc).__name__}", False))

    @staticmethod
    def _api_error_message(resp):
        try:
            error = resp.json().get("error", {})
            message = clean_text(error.get("message", ""), 250)
            reasons = [clean_text(i.get("reason"), 80) for i in error.get("errors", []) if i.get("reason")]
            if reasons:
                message += " [" + ", ".join(reasons[:3]) + "]"
            return message or "상세 오류 메시지가 없습니다."
        except (ValueError, TypeError, AttributeError):
            return "상세 오류 메시지를 읽을 수 없습니다."

    @staticmethod
    def _fetch_video_details(headers, data):
        """재생시간과 공식 합성 콘텐츠 라벨 조회(1 unit). 실패 시 None, 조회할 ID 가 없으면 {}."""
        ids = []
        for item in data.get("items", []):
            vid = (item.get("id") or {}).get("videoId", "")
            if VIDEO_ID_PATTERN.fullmatch(str(vid)):
                ids.append(vid)
        if not ids:
            return {}
        try:
            resp = requests.get(VIDEOS_URL, headers=headers, timeout=REQUEST_TIMEOUT,
                                params={"part": "contentDetails,status", "id": ",".join(ids)})
            if resp.status_code != 200:
                return None
            details = {}
            for item in resp.json().get("items", []):
                details[item.get("id")] = {
                    "duration": parse_iso_duration((item.get("contentDetails") or {}).get("duration", "")),
                    "synthetic": (item.get("status") or {}).get("containsSyntheticMedia", False) is True,
                }
            return details
        except (requests.RequestException, ValueError, TypeError):
            return None

    def _poll_result(self):
        try:
            msg = self.result_queue.get_nowait()
        except queue.Empty:
            if self.winfo_exists():
                self.after(100, self._poll_result)
            return

        self.set_busy(False)
        if msg[0] == "ok":
            try:
                videos, shorts = self.process_api_response(msg[1], msg[2], msg[3])
                self.show_results(videos)
                if not videos:
                    self.update_status(f"표시할 결과가 없습니다. (쇼츠 {shorts}개 제외)", "orange")
                elif msg[3] is None:
                    self.update_status("공식 AI 라벨·길이 확인에 실패해 제목/설명 규칙으로만 판별했습니다 "
                                       f"(캐시 미저장). 쇼츠 확인 불가.", "orange")
                else:
                    excluded = sum(1 for v in videos if v["status"] == "제외")
                    self.update_status(f"검색 및 판별 완료: {len(videos)}개 표시(자동 제외 후보 {excluded}개), "
                                       f"쇼츠 {shorts}개 제외. 결과는 참고용입니다.", "green")
            except (sqlite3.Error, ValueError, TypeError) as exc:
                self.update_status(f"결과 처리 오류: {type(exc).__name__}", "red")
        else:
            if msg[2]:
                self.refund_search_count()
            self.update_status(msg[1], "red")
        self.update_quota_display()

